"""Editorial rewriting layer for blog posts to eliminate watermarks and polish style.

Takes the draft generated by Claude and runs an executive copy-editing pass
via a secondary provider (Google Gemini or OpenAI) to dismantle token-level
watermarks, vary cadence and burstiness, and elevate analytical prose while
preserving facts, Markdown structure, and citation anchors verbatim.
"""

import json
import logging
import os
import re
from dataclasses import dataclass
from typing import Dict, Optional

logger = logging.getLogger(__name__)

_REWRITE_SYSTEM = """You are a master executive copy editor for a top-tier business and technology publication.
Your job is to rewrite and polish the supplied article draft so it reads like authoritative, human-crafted strategic analysis.

Crucial Objectives:
1. Editorial Polish & Burstiness: Restructure sentences to vary rhythm, cadence, and length. Mix concise punchy observations with nuanced analysis. Eliminate robotic phrasing, passive constructions, and repetitive sentence openings.
2. Grounding & Fidelity: Preserve EVERY factual claim, dataset, company name, quote, and analytical argument. Do not invent facts, and do not remove the factual basis of any claim.
3. Strict Markdown Structure Preservation:
   - Preserve all H2 section headings (e.g., `## The Strategic Read` must remain verbatim).
   - Preserve all inline citations and hyperlinks verbatim.
   - Do NOT add a "## Sources" section (the publishing system generates that separately).
   - Do NOT use em dashes (-- or —); use clean commas, semicolons, or parentheses.
   - Avoid AI clichés: "delve", "landscape", "testament", "underscore", "pivotal", "in today's world", "game-changer".
4. Article Length Requirement: The rewritten body_markdown MUST be a comprehensive, long-form analytical article between 950 and 1,300 words. Do NOT summarize, outline, or truncate. Rewrite every section and paragraph with substantive, in-depth prose.

Return a JSON object with:
- title: polished, compelling headline
- subtitle: sharp, one-sentence dek
- excerpt: 35-60 words
- body_markdown: the full rewritten article body in Markdown (950-1300 words)
"""


BANNED_REPLACEMENTS = {
    r"\bin today's fast-paced world\b": "in current market conditions",
    r"\bit's important to note\b": "notably",
    r"\bthis underscores\b": "this highlights",
    r"\bunderscores\b": "highlights",
    r"\bdelve\b": "examine",
    r"\bdelving\b": "examining",
    r"\blandscape\b": "environment",
    r"\blandscapes\b": "environments",
    r"\bgame-changer\b": "major shift",
    r"\bgame-changing\b": "transformative",
    r"\bnavigating\b": "managing",
    r"\bnavigate\b": "manage",
    r"\brobust\b": "resilient",
}


def sanitize_editorial_text(text: str) -> str:
    if not text:
        return text
    # Replace em dashes
    cleaned = text.replace("—", ", ").replace("–", "-")
    for pattern, replacement in BANNED_REPLACEMENTS.items():
        cleaned = re.sub(pattern, replacement, cleaned, flags=re.IGNORECASE)
    return cleaned


@dataclass
class RewriteResult:
    title: str
    subtitle: str
    excerpt: str
    body_markdown: str


class BlogArticleRewriter:
    def __init__(
        self,
        provider: Optional[str] = None,
        gemini_api_key: Optional[str] = None,
        gemini_model: Optional[str] = None,
        openai_api_key: Optional[str] = None,
        openai_model: Optional[str] = None,
    ):
        self.gemini_api_key = gemini_api_key or os.environ.get("GEMINI_API_KEY")
        self.gemini_model = gemini_model or os.environ.get("GEMINI_MODEL", "gemini-3.8-flash")
        self.openai_api_key = openai_api_key or os.environ.get("OPENAI_API_KEY")
        self.openai_model = openai_model or os.environ.get("OPENAI_MODEL", "gpt-4o-mini")

        preferred_provider = provider or os.environ.get("BLOG_REWRITE_PROVIDER")
        if preferred_provider:
            self.provider = preferred_provider.lower().strip()
        elif self.openai_api_key:
            self.provider = "openai"
        elif self.gemini_api_key:
            self.provider = "gemini"
        else:
            self.provider = "none"

    def is_available(self) -> bool:
        return self.provider in {"gemini", "openai"}

    def rewrite(
        self,
        title: str,
        subtitle: str,
        excerpt: str,
        body_markdown: str,
    ) -> RewriteResult:
        """Run the editorial pass using the configured secondary model."""
        if self.provider == "gemini":
            res = self._rewrite_with_gemini(title, subtitle, excerpt, body_markdown)
        elif self.provider == "openai":
            res = self._rewrite_with_openai(title, subtitle, excerpt, body_markdown)
        else:
            logger.info("No secondary model configured; returning original draft.")
            return RewriteResult(title, subtitle, excerpt, body_markdown)

        # Validate structural integrity
        headings = re.findall(r"^##\s+(.+?)\s*$", res.body_markdown, re.MULTILINE)
        words = len(re.findall(r"\b[\w’'-]+\b", res.body_markdown))
        if words < 850 or not (3 <= len(headings) <= 5) or (headings and headings[-1] != "The Strategic Read"):
            print(
                f"WARN: Rewritten draft failed structural validation (words: {words}, "
                f"H2 count: {len(headings)}, final H2: '{headings[-1] if headings else ''}'). "
                "Falling back to primary draft."
            )
            return RewriteResult(title, subtitle, excerpt, body_markdown)
        return res

    def _rewrite_with_gemini(
        self,
        title: str,
        subtitle: str,
        excerpt: str,
        body_markdown: str,
    ) -> RewriteResult:
        from google import genai

        client = genai.Client(api_key=self.gemini_api_key)
        prompt = (
            f"{_REWRITE_SYSTEM}\n\n"
            f"DRAFT TO REWRITE:\n"
            f"TITLE: {title}\n"
            f"SUBTITLE: {subtitle}\n"
            f"EXCERPT: {excerpt}\n\n"
            f"BODY MARKDOWN:\n{body_markdown}\n\n"
            "Return valid JSON only."
        )

        response = client.models.generate_content(
            model=self.gemini_model,
            contents=prompt,
        )
        text = response.text.strip()
        fenced = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", text, re.DOTALL)
        if fenced:
            text = fenced.group(1).strip()

        data = json.loads(text)
        return RewriteResult(
            title=sanitize_editorial_text(data.get("title", title)),
            subtitle=sanitize_editorial_text(data.get("subtitle", subtitle)),
            excerpt=sanitize_editorial_text(data.get("excerpt", excerpt)),
            body_markdown=sanitize_editorial_text(data.get("body_markdown", body_markdown)),
        )

    def _rewrite_with_openai(
        self,
        title: str,
        subtitle: str,
        excerpt: str,
        body_markdown: str,
    ) -> RewriteResult:
        import httpx

        headers = {
            "Authorization": f"Bearer {self.openai_api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.openai_model,
            "response_format": {"type": "json_object"},
            "messages": [
                {"role": "system", "content": _REWRITE_SYSTEM},
                {
                    "role": "user",
                    "content": (
                        f"DRAFT TO REWRITE:\n"
                        f"TITLE: {title}\n"
                        f"SUBTITLE: {subtitle}\n"
                        f"EXCERPT: {excerpt}\n\n"
                        f"BODY MARKDOWN:\n{body_markdown}"
                    ),
                },
            ],
            "temperature": 0.7,
            "max_tokens": 4096,
        }

        resp = httpx.post("https://api.openai.com/v1/chat/completions", headers=headers, json=payload, timeout=60)
        resp.raise_for_status()
        data = json.loads(resp.json()["choices"][0]["message"]["content"])
        return RewriteResult(
            title=sanitize_editorial_text(data.get("title", title)),
            subtitle=sanitize_editorial_text(data.get("subtitle", subtitle)),
            excerpt=sanitize_editorial_text(data.get("excerpt", excerpt)),
            body_markdown=sanitize_editorial_text(data.get("body_markdown", body_markdown)),
        )
